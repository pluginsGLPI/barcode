use Glpi\Exception\Http\AccessDeniedHttpException;
use Glpi\Exception\Http\BadRequestHttpException;
use Glpi\Exception\Http\NotFoundHttpException;

/**
 * Download a file generated by the plugin.
 *
 * Generated files are prefixed by the owner user ID ("{users_id}_...") and can
 * only be downloaded by their owner. The company logo is readable by any
 * logged-in user (it is printed on every label).
 */

Session::checkLoginUser();

$filename = basename((string) ($_GET['file'] ?? ''));
if ($filename === '') {
   throw new BadRequestHttpException();
}

$mimes = [
   'pdf' => 'application/pdf',
   'zip' => 'application/zip',
   'png' => 'image/png',
];
$extension = strtolower(pathinfo($filename, PATHINFO_EXTENSION));
if (!isset($mimes[$extension])) {
   throw new BadRequestHttpException();
}

$owner_prefix = Session::getLoginUserID() . '_';
if ($filename === 'logo.png') {
   $download_name = $filename;
} else if (str_starts_with($filename, $owner_prefix)) {
   // Do not expose the internal user prefix in the downloaded file name
   $download_name = substr($filename, strlen($owner_prefix));
} else {
   throw new AccessDeniedHttpException();
}

$path = GLPI_PLUGIN_DOC_DIR . '/barcode/' . $filename;
if (!is_file($path)) {
   throw new NotFoundHttpException();
}

return Toolbox::getFileAsResponse($path, $download_name, $mimes[$extension]);
